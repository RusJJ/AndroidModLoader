# Rebuilds include/dex_dialogs.h from java/ (needs JDK 11+ on PATH, Android SDK with build-tools and a platform)
$SDKPath = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { "$env:LOCALAPPDATA/Android/Sdk" }
$AndroidJar = (Get-ChildItem "$SDKPath/platforms" | Sort-Object Name | Select-Object -Last 1).FullName + "/android.jar"
$D8Jar = (Get-ChildItem "$SDKPath/build-tools" | Sort-Object Name | Select-Object -Last 1).FullName + "/lib/d8.jar"
$OutDir = "$PSScriptRoot/out"

Remove-Item -Recurse -Force $OutDir -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force $OutDir | Out-Null

& javac -source 8 -target 8 -Xlint:-options -cp $AndroidJar -d $OutDir (Get-ChildItem -Recurse "$PSScriptRoot/net" -Filter *.java).FullName
if ($LASTEXITCODE -ne 0) { Exit $LASTEXITCODE }
& java -cp $D8Jar com.android.tools.r8.D8 --release --min-api 21 --lib $AndroidJar --output $OutDir (Get-ChildItem -Recurse $OutDir -Filter *.class).FullName
if ($LASTEXITCODE -ne 0) { Exit $LASTEXITCODE }

$bytes = [System.IO.File]::ReadAllBytes("$OutDir/classes.dex")
$lines = for ($i = 0; $i -lt $bytes.Length; $i += 16)
{
    "    " + (($bytes[$i..([Math]::Min($i + 15, $bytes.Length - 1))] | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", ") + ","
}
$header = @("// Generated by java/build_dex.ps1 from java/net/rusjj/aml/Dialogs.java, do not edit", "#pragma once", "", "static const uint8_t g_DialogsDex[] = {") + $lines + @("};", "")
[System.IO.File]::WriteAllLines("$PSScriptRoot/../include/dex_dialogs.h", $header)

Remove-Item -Recurse -Force $OutDir
Write-Output "Done: include/dex_dialogs.h ($($bytes.Length) bytes)"
